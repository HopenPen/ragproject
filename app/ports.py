# Назначение файла: минимальные порты к транзакциям, файлам, модели и security.
from typing import Protocol, Any


class Repository(Protocol):
    def get(self, table: str, id: str, lock: bool = False) -> dict | None: ...
    def find(self, table: str, **filters) -> list[dict]: ...
    def add(self, table: str, **values) -> dict: ...
    def update(self, table: str, id: str, **values) -> dict: ...
    def delete(self, table: str, id: str) -> None: ...
    def lock_admins(self) -> None: ...
    def search(self, corpus_id: str, q: str, scope: str) -> list[dict]: ...


class UnitOfWork(Protocol):
    repo: Repository
    def __enter__(self) -> 'UnitOfWork': ...
    def __exit__(self, *args) -> None: ...
    def commit(self) -> None: ...


class FileStorage(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def get(self, key: str) -> bytes: ...
    def inspect_pdf(self, data: bytes) -> dict: ...
    def prepare_page(self, data: bytes, number: int) -> dict: ...


class ModelClient(Protocol):
    def call(self, purpose: str, schema: dict, pages: list[dict], context: dict) -> dict: ...


class TaskPublisher(Protocol):
    def publish(self, item_id: str, task_id: str) -> None: ...
    def dead_letter(self, payload: dict) -> None: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, hashed: str, password: str) -> bool: ...


class TokenIssuer(Protocol):
    def issue(self, user: dict) -> str: ...


class LoginLimiter(Protocol):
    def check(self, identity: str) -> None: ...


class Cache(Protocol):
    def get(self, key: str) -> Any: ...
    def put(self, key: str, value: Any, ttl: int = 30) -> None: ...
